        # 10. cage-tier removed entirely: every claiming pod widens to
        #    uncaged -- patch, again no special case.
        m6 = classify_cage_tier("cage-tier", old_dir / "cage-tier.yaml", None, pods)
        assert m6.verdict == "patch", m6

        # 11. "the gate never estimates viability... it prints one sentence
        #     instead" -- the major-narrowing detail is one sentence (no
        #     newline, no bullet points) and carries no viability language.
