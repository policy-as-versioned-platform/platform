#!/usr/bin/env python3
"""cage_engine.py -- ticket cs-21: cage-spec comparison and the computed bump.

The core classification engine gate.py's `run_gate` calls once a repository
state carries a real old subject tree, a real new subject tree, and a
generated corpus (ticket 19). Two tracks combine into one whole-body bump,
exactly the way `CONTEXT.md`'s "a policy version covers the whole body"
already combines named-policy verdicts in rederive_bumps.py (reused here,
never re-derived, per spec.md's "Pairing and structural rules": "Major and
patch come from verdict movement. Minor comes from presence plus
`validationActions`."):

  Track 1 -- ValidatingPolicy admission. `rederive_bumps.classify_policy`,
  called per paired policy file -- UNCHANGED for the add/removed/legacy
  cases (still the exact function, same primitives). When BOTH sides are
  present and at least one self-scopes (cs-16's own fix, see
  `classify_validating`/`_neutralize_self_scope` below), the pair is
  classified against a COPY of each side with its `only-this-policy-version`
  matchConditions entry neutralized to `true` before `classify_policy` ever
  runs -- see that function's docstring for why. major = an existing
  policy's admission verdict narrows (admitted -> refused) for some corpus
  pod, or a brand-new Deny policy is added; minor = a brand-new Audit-only
  policy is added (it cannot refuse anything -- ticket 02's own resolution);
  patch = the passing set only ever widens. Reads per-policy outcomes, never
  a pooled CLI exit code -- `rederive_bumps.cel_pass` already calls
  `kyverno apply` one policy file at a time (ticket 01's own finding, reused
  directly rather than re-derived).

  Track 2 -- the cage/enforcement dial spec (spec.md, "What the gate
  measures": "Every workload is always caged, and the cage spec is what
  changes... the engine compares cage specs, not verdict enums"). cage-tier
  (graded/policies/cage-tier.yaml, a MutatingPolicy) has no
  `validationActions` and no pass/fail of its own -- `kyverno apply` always
  mutates, never fails -- so Track 1's admitted/refused vocabulary does not
  apply to it. For each corpus pod that claims a policy version, this
  computes the dial VALUES the pod would receive under the old body and the
  new body (a pure map lookup on the pod's `posture.acme.io/tier` label,
  defaulted to 'baseline' exactly as cage-tier.yaml's own CEL does -- see
  `effective_tier`) and classifies major when the new spec is not AT LEAST
  AS PERMISSIVE as the old one, at the SPEC level: a permissiveness partial
  order across the same fields graded/cage.py's TIERS table names (cpu, mem,
  priorityClass, dropAll, readOnlyRootFs, waf) -- never an enumerated list
  of surfaces. A tier policy that appends a sidecar, sets a priority class,
  flips two securityContext fields and drops capabilities all in one release
  still classifies from ONE spec-level comparison, not four separate dial
  checks that rot on the next mutation added.

  "There is no uncaged state" (spec.md) is modelled as the TOP of the
  permissiveness lattice: a pod cage-tier does not reach at all (the file
  absent on one side, or the pod does not claim a version) receives the
  fully-permissive degenerate spec, UNCAGED. "cage-tier newly added" then
  falls out of the SAME per-pod comparison as any other tightening (uncaged
  -> a real tier is a narrowing, hence major) with no special case, and
  "cage-tier removed" falls out as a widening (patch), also with no special
  case -- neither needs its own branch.

Movement entries name the corpus entries that moved (the pod filenames) and
the CEL expression responsible: the sole `validations[]` expression for a
Track 1 policy (every corpus policy body carries exactly one), or the
`dial` variable's own CEL expression for Track 2 (the one expression that
encodes every tier's dial values -- spec-level, not per-dial).

A policy `kind` this engine does not model (GeneratingPolicy, a plain
PriorityClass, a MutatingPolicy with no `dial` variable such as
posture/policies/stamp-posture.yaml) is skipped, not guessed at -- ponytail:
the two tracks above are what this ticket names; a third surface is a future
ticket's job.

cs-16 fix (was: "ponytail: a genuine, disclosed gap"): a corpus generated by
corpus_generator.main()'s LIVE default path (both subjects materialized from
real released version trees, one shared `inside_pin` baked into every pod,
exactly as its own docstring says: "one declared 'inside' pin ... is a
property of the version under test, not of old vs new") pins every pod to
the NEW version only (plus a fixed OUTSIDE_PIN placeholder -- never the OLD
version, with one narrow exception the corpus's own expr-pin axis carves out
for a policy's OWN self-scope predicate). A self-scoped mandatory-member
policy (render-version-tree.py's `only-this-policy-version` matchCondition)
on the OLD side then matches almost none of those pods, so it reads as
trivially admitted (kyverno `skip`, not a real pass) for nearly all of them
-- and if the NEW side's copy denies some of those same pods on grounds that
have nothing to do with the version bump (e.g. posture-trust-boundary's own
`variables.posture == variables.claimed` correctly firing on a forged-posture
fixture the corpus generates on purpose), this showed up as a spurious major
that had nothing to do with the OLD and NEW policy BODIES actually
differing. Proven for real: `kyverno apply` against the real
v2.0.0/v2.0.1 posture-trust-boundary bodies -- byte-identical modulo the
version literal -- returns `skip: 1` for v2.0.0 and a real `fail: 1` for
v2.0.1 against the SAME forged-posture corpus pod. The three known-good
historical bumps rederive_bumps.py rederives predate self-scoping entirely
(they use the old `objectSelector` placeholder scheme, not
render-version-tree.py's matchConditions self-scope) and so never hit this.

The fix is NOT "relabel the pod's own version-pin claim per side" (a version
that first looked right and is now proven wrong on the very case that
motivated it): posture-trust-boundary's own validation reads
`variables.claimed` straight off the pod's PIN_LABEL as a REAL business-logic
input ("posture must equal the claimed version"), not merely as a
self-scope detail -- overwriting PIN_LABEL to satisfy one side's self-scope
changes what that side's validation is actually testing, breaking the very
posture-vs-claim relationship the corpus deliberately crafted (a fixture
built to be "posture matches claim" would silently become "posture is
forged" for the relabeled side, purely as an artifact of the relabel, not a
real difference). The fix instead neutralizes ONLY the named
`only-this-policy-version` matchConditions entry itself (render-version-tree
_self_scope's own, stable, machine-generated name -- see
`_neutralize_self_scope`) to an always-true expression, on a COPY of each
side, leaving the pod, every OTHER matchCondition, every variable and every
validation completely untouched. Both sides are then asked kyverno's real
question -- "does the REST of this body admit or refuse this pod" -- on
equal footing: a version-literal-only pair neutralizes to byte-identical
bodies (verdict "none"), and a real behavioral change survives neutralizing
untouched (still detected). This generalizes correctly to the case where a
version bump carries BOTH a version-literal change and a real content
change in the same release -- only the named self-scope entry is ever
touched.

Usage:
    cage_engine.py --selfcheck
"""
