_CAGE_TIER_TMPL = """\
apiVersion: policies.kyverno.io/v1alpha1
kind: MutatingPolicy
metadata:
  name: cage-tier
spec:
  matchConstraints:
    resourceRules:
      - apiGroups: [""]
        apiVersions: ["v1"]
        operations: ["CREATE", "UPDATE"]
        resources: ["pods"]
  matchConditions:
    - name: claims-a-policy-version
      expression: >-
        object.metadata.?labels['policy-as-versioned.dev/policy-version'].orValue('') != ''
  variables:
    - name: dial
      expression: >-
        {DIAL}[variables.tier]
"""


def _dial_literal(baseline_cpu="500m", baseline_mem="256Mi", baseline_waf="0",
                   baseline_pc="cage-baseline"):
    return (
        "{'baseline':{'cpu':'%s','mem':'%s','pc':'%s','harden':'false',"
        "'wafCpu':'%s','wafMem':'0'},"
        "'restricted':{'cpu':'250m','mem':'128Mi','pc':'cage-restricted','harden':'true',"
        "'wafCpu':'100m','wafMem':'128Mi'},"
        "'quarantine':{'cpu':'100m','mem':'64Mi','pc':'cage-quarantine','harden':'true',"
        "'wafCpu':'250m','wafMem':'256Mi'}}"
        % (baseline_cpu, baseline_mem, baseline_pc, baseline_waf)
    )


def _write_cage_tier(path: Path, **dial_kwargs) -> None:
    path.write_text(_CAGE_TIER_TMPL.format(DIAL=_dial_literal(**dial_kwargs)))


def _write_pod(path: Path, name: str, tier: str | None, claims: bool = True) -> None:
    labels = {}
    if claims:
        labels[PIN_LABEL] = "1.0.0"
    if tier is not None:
        labels[TIER_LABEL] = tier
    yaml_doc = {
        "apiVersion": "v1", "kind": "Pod",
        "metadata": {"name": name, "labels": labels},
        "spec": {"containers": [{"name": "app", "image": "nginx:1.25"}]},
    }
    path.write_text(yaml.safe_dump(yaml_doc))


def selfcheck() -> None:
    import tempfile

    # 1. dial_table parses the REAL cage-tier.yaml body without error, and
    #    the three tiers it names match graded/cage.py's own TIERS keys --
    #    a smoke test against the real, not just a synthetic, file.
    repo = Path(__file__).resolve().parent.parent
    real_body = yaml.safe_load((repo / "graded" / "policies" / "cage-tier.yaml").read_text())
    real_table, real_expr = dial_table(real_body)
    assert set(real_table) == {"baseline", "restricted", "quarantine"}, real_table
    assert real_table["baseline"].cpu == 500 and real_table["quarantine"].cpu == 100, real_table
    assert real_table["baseline"].drop_all is False and real_table["quarantine"].drop_all is True
    assert "variables.tier" in real_expr

    # 2. the permissiveness lattice: UNCAGED is at least as permissive as
    #    every real tier, and no real tier is at least as permissive as
    #    UNCAGED (going from unrestricted to any real cage always narrows).
    for t in ("baseline", "restricted", "quarantine"):
        ok, regressed, _ = at_least_as_permissive(UNCAGED, real_table[t])
        assert not ok and regressed, (t, regressed)
        ok2, _, _ = at_least_as_permissive(real_table[t], UNCAGED)
        assert ok2

    # 3. tighter tiers are strictly less permissive than looser ones, on
    #    every field the ticket names.
    b, r, q = real_table["baseline"], real_table["restricted"], real_table["quarantine"]
    for tighter, looser in ((r, b), (q, r), (q, b)):
        ok, regressed, _ = at_least_as_permissive(looser, tighter)
        assert not ok and regressed, (looser, tighter, regressed)

    with tempfile.TemporaryDirectory() as td:
        td = Path(td)

        # 4. Track 2, a genuine tightening: baseline's cpu limit drops
        #    500m -> 250m between old and new. A pod at the (defaulted)
        #    baseline tier must classify major, name itself as a moved
        #    corpus entry, and name the `dial` CEL expression -- never an
        #    enumerated "cpu changed" surface list.
        old_dir, new_dir = td / "old", td / "new"
        old_dir.mkdir(); new_dir.mkdir()
        _write_cage_tier(old_dir / "cage-tier.yaml", baseline_cpu="500m")
        _write_cage_tier(new_dir / "cage-tier.yaml", baseline_cpu="250m")
        pods_dir = td / "pods"
        pods_dir.mkdir()
        _write_pod(pods_dir / "claiming-default-tier.yaml", "p1", tier=None)
        _write_pod(pods_dir / "claiming-restricted.yaml", "p2", tier="restricted")
        _write_pod(pods_dir / "not-claiming.yaml", "p3", tier="baseline", claims=False)
        pods = sorted(pods_dir.glob("*.yaml"))

        m = classify_cage_tier("cage-tier", old_dir / "cage-tier.yaml", new_dir / "cage-tier.yaml", pods)
        assert m.verdict == "major", m
        assert "claiming-default-tier" in m.entries, m.entries  # absent tier label defaults to baseline
        assert "claiming-restricted" not in m.entries, m.entries  # restricted's dials untouched
        assert "not-claiming" not in m.entries, m.entries  # never matched by cage-tier at all
        assert m.expressions == [_dial_literal(baseline_cpu="250m") + "[variables.tier]"], m.expressions

        # 5. a widen-only change (baseline's mem raised) classifies patch,
        #    never major, and names the widened entry.
        _write_cage_tier(new_dir / "cage-tier.yaml", baseline_cpu="500m", baseline_mem="512Mi")
        m2 = classify_cage_tier("cage-tier", old_dir / "cage-tier.yaml", new_dir / "cage-tier.yaml", pods)
        assert m2.verdict == "patch", m2
        assert "claiming-default-tier" in m2.entries, m2.entries

        # 6. no change at all classifies none.
        _write_cage_tier(new_dir / "cage-tier.yaml", baseline_cpu="500m")
        m3 = classify_cage_tier("cage-tier", old_dir / "cage-tier.yaml", new_dir / "cage-tier.yaml", pods)
        assert m3.verdict == "none" and m3.entries == [], m3

        # 7. spec-level, not dial-level: ONE field regresses (cpu tightens)
        #    while ANOTHER improves in the SAME release (waf drops from
        #    'light' to 'none' on baseline) -- still major. A partial order
        #    never lets one field's improvement excuse another's regression.
        _write_cage_tier(old_dir / "cage-tier.yaml", baseline_cpu="500m", baseline_waf="100m")
        _write_cage_tier(new_dir / "cage-tier.yaml", baseline_cpu="250m", baseline_waf="0")
        m4 = classify_cage_tier("cage-tier", old_dir / "cage-tier.yaml", new_dir / "cage-tier.yaml", pods)
        assert m4.verdict == "major", m4
        assert "cpu" in m4.detail, m4.detail  # named the field that actually regressed
        _write_cage_tier(old_dir / "cage-tier.yaml", baseline_cpu="500m")  # restore for the rest

        # 8. cs-21 regression guard: priorityClass permissiveness must come
        #    from the ACTUAL assigned PriorityClass value, not from a rank
        #    re-derived off the pod's own tier label. Every OTHER field is
        #    held identical; only baseline's `pc` is repointed from
        #    'cage-baseline' (real value -10) to 'cage-quarantine' (real
        #    value -1000, see graded/policies/priorityclasses.yaml) -- a
        #    real narrowing (workload evicted far sooner under pressure). The
        #    old (pre-fix) code derived priorityClass purely from
        #    TIER_ORDER.index(tier_name), and BOTH sides look up the SAME
        #    tier key ('baseline') for this pod -- so tier_name was identical
        #    on both sides BY CONSTRUCTION and this real change was
        #    completely invisible (verdict came back "none"). Proven by
        #    breaking the fix (reverting permissive_rank to key off tier_name
        #    again) and confirming this assertion fails before restoring it.
        _write_cage_tier(old_dir / "cage-tier.yaml", baseline_pc="cage-baseline")
        _write_cage_tier(new_dir / "cage-tier.yaml", baseline_pc="cage-quarantine")
        m_pc = classify_cage_tier("cage-tier", old_dir / "cage-tier.yaml", new_dir / "cage-tier.yaml", pods)
        assert m_pc.verdict == "major", m_pc
        assert "claiming-default-tier" in m_pc.entries, m_pc.entries
        assert "priorityClass" in m_pc.detail, m_pc.detail  # named the field that actually regressed
        _write_cage_tier(old_dir / "cage-tier.yaml", baseline_pc="cage-baseline")  # restore for the rest
        _write_cage_tier(new_dir / "cage-tier.yaml", baseline_cpu="500m")  # restore for the rest

        # 9. cage-tier newly added (absent on old side entirely): every
        #    claiming pod narrows from the uncaged top of the lattice -- no
        #    special case, it falls out of the same per-pod comparison.
        m5 = classify_cage_tier("cage-tier", None, new_dir / "cage-tier.yaml", pods)
        assert m5.verdict == "major", m5
        assert set(m5.entries) == {"claiming-default-tier", "claiming-restricted"}, m5.entries

        # 10. cage-tier removed entirely: every claiming pod widens to
        #    uncaged -- patch, again no special case.
        m6 = classify_cage_tier("cage-tier", old_dir / "cage-tier.yaml", None, pods)
        assert m6.verdict == "patch", m6

        # 11. "the gate never estimates viability... it prints one sentence
        #     instead" -- the major-narrowing detail is one sentence (no
        #     newline, no bullet points) and carries no viability language.
        assert "\n" not in m.detail, m.detail
        for word in ("viable", "viability", "%", "estimate", "workloads would"):
            assert word not in m.detail.lower(), (word, m.detail)

    # 12. Track 1: unchanged, direct reuse of rederive_bumps.classify_policy
    #     (not re-derived) -- proves the refactor point of this ticket
    #     without duplicating ticket 01's own logic.
    fx = rederive_bumps.ALL_FIXTURES
    dept_old = rederive_bumps.CORPUS / "department-label-1.0.0.yaml"
    dept_new = rederive_bumps.CORPUS / "department-label-2.0.0.yaml"
