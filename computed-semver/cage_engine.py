    # 12. Track 1: unchanged, direct reuse of rederive_bumps.classify_policy
    #     (not re-derived) -- proves the refactor point of this ticket
    #     without duplicating ticket 01's own logic.
    fx = rederive_bumps.ALL_FIXTURES
