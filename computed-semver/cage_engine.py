        "regressing while another improves is still major (spec-level, not "
        "dial-level); priorityClass ranks on the ACTUAL assigned PriorityClass's "
        "real value, so a tier's pc field repointed at a different PriorityClass "
        "registers as major even with every other dial untouched (cs-21 regression "
        "guard); cage-tier added/removed fall out of the same per-pod "
        "comparison with no special case; the major detail is one sentence with no "
